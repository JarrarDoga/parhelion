#!/bin/sh
# Embeds a TrueType font as base64 in Swift source.
#
# Usage: Scripts/embed-font.sh Fonts/Inter-Regular.ttf > Sources/ParhelionRender/InterRegularFontData.swift
#
# Parhelion cannot ship SwiftPM resources (docs/adr/0003-no-swiftpm-resources.md),
# so the font the renderer draws with is compiled into the library instead.
set -eu
font="$1"
printf '// Generated by Scripts/embed-font.sh from %s.\n' "$font"
printf '// Do not edit this file by hand.\n\n'
printf '// swift-format-ignore-file\n\n'
printf '/// The bytes of %s, base64-encoded.\n' "$(basename "$font")"
printf 'let interRegularFontBase64 = "%s"\n' "$(base64 -w 0 "$font")"
