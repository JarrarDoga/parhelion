#!/bin/sh
# Embeds the Phosphor icons that Symbols/symbols.txt maps SF Symbol names to,
# as SVG path data in Swift source.
#
# Usage:
#   npm pack @phosphor-icons/core@2.1.1 && tar xzf phosphor-icons-core-2.1.1.tgz
#   Scripts/embed-symbols.sh package > Sources/ParhelionUI/PhosphorSymbolData.swift
#
# The argument is the extracted npm package, the directory that contains
# `assets/regular` and `assets/fill`. The script reads only those files and
# Symbols/symbols.txt, and never downloads anything.
#
# Apple's license does not allow shipping SF Symbols outside Apple platforms, so
# Parhelion draws symbol images with Phosphor Icons (MIT; see
# Symbols/Phosphor-LICENSE.txt). Parhelion cannot ship SwiftPM resources
# (docs/adr/0003-no-swiftpm-resources.md), so the paths are compiled into the
# library, and only the mapped icons are included.
set -eu
package="$1"
repo="$(cd "$(dirname "$0")/.." && pwd)"
mapping="$repo/Symbols/symbols.txt"
version="$(sed -n 's/^ *"version": *"\([^"]*\)".*/\1/p' "$package/package.json")"

# The mapping without comments and blank lines.
entries() {
    grep -v '^#' "$mapping" | grep -v '^[[:space:]]*$'
}

# The path data of one SVG file. Every Phosphor icon is a single path.
path_data() {
    sed -n 's/.*<path d="\([^"]*\)".*/\1/p' "$1"
}

printf '// Generated by Scripts/embed-symbols.sh from @phosphor-icons/core %s and\n' "$version"
printf '// Symbols/symbols.txt. Do not edit this file by hand.\n\n'
printf '// swift-format-ignore-file\n\n'
printf '/// The Phosphor icon that draws each SF Symbol name, without a `.fill` suffix.\n'
printf 'let phosphorIconNames: [String: String] = [\n'
entries | LC_ALL=C sort | while read -r symbol icon; do
    printf '    "%s": "%s",\n' "$symbol" "$icon"
done
printf ']\n\n'
printf '/// The outline of each Phosphor icon in its regular and fill weights, as SVG\n'
printf '/// path data on a 256-unit grid.\n'
printf 'let phosphorIconPaths: [String: (regular: String, fill: String)] = [\n'
entries | while read -r symbol icon; do printf '%s\n' "$icon"; done | LC_ALL=C sort -u |
    while read -r icon; do
        regular="$package/assets/regular/$icon.svg"
        fill="$package/assets/fill/$icon-fill.svg"
        if [ ! -f "$regular" ] || [ ! -f "$fill" ]; then
            echo "embed-symbols.sh: Phosphor has no icon named $icon" >&2
            exit 1
        fi
        printf '    "%s": (\n' "$icon"
        printf '        "%s",\n' "$(path_data "$regular")"
        printf '        "%s"\n' "$(path_data "$fill")"
        printf '    ),\n'
    done
printf ']\n'
